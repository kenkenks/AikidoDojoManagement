import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const files=['Flow','StorageId','MemberObject','DAO_Definitions','DAO_Business','SystemContext','TimeTravel','TimeApplication'];
const sources=Object.fromEntries(files.map(name=>['./'+name+'.js',fs.readFileSync(path.join(root,'shared',name+'.js'),'utf8')]));
sources['./DAO_Core.js']=fs.readFileSync(path.join(root,'adapters/gas/DAO_Core.js'),'utf8');
const modules=Object.entries(sources).map(([name,source])=>JSON.stringify(name)+':function(module,exports,require){\n'+source+'\n}').join(',\n');
const output='/* Generated: node tools/build-time-travel.mjs */\nvar DojoTimeTravel=(function(){const modules={'+modules+'};const cache={};function require(name){if(!Object.prototype.hasOwnProperty.call(modules,name))throw new Error(name);if(!cache[name]){const m={exports:{}};cache[name]=m;modules[name](m,m.exports,require);}return cache[name].exports;}return require("./TimeApplication.js");})();\n';
fs.writeFileSync(path.join(root,'gas/DojoTimeTravel.js'),output);
console.log('Generated gas/DojoTimeTravel.js');
